#!/bin/bash
#
# Creates a self-signed code-signing certificate in your login keychain and
# points Debug builds at it (via the git-ignored Configuration/LocalSigning.xcconfig).
#
# Why: ad-hoc signed builds get a new identity on every rebuild, so macOS asks
# for Calendar access (and similar permissions) again each time. A stable local
# certificate keeps the app's identity the same across rebuilds.
#
# Usage: scripts/setup-local-signing.sh [--force]
#   --force   replace an existing LocalSigning.xcconfig
#
# Prompts you can expect: macOS asks for your login password once to trust the
# certificate for code signing. No Apple Developer account is needed.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_PATH="${CONFIG_PATH:-$ROOT_DIR/Configuration/LocalSigning.xcconfig}"
CERT_NAME="${CERT_NAME:-ZoneBar Local Signing}"
KEYCHAIN="${KEYCHAIN:-$HOME/Library/Keychains/login.keychain-db}"
SKIP_TRUST="${SKIP_TRUST:-0}"
# macOS's bundled LibreSSL writes PKCS#12 files that `security import` accepts;
# Homebrew's OpenSSL 3 does not by default.
OPENSSL=/usr/bin/openssl
FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1

if [[ -e "$CONFIG_PATH" && "$FORCE" != "1" ]]; then
    echo "Configuration/LocalSigning.xcconfig already exists; leaving it alone."
    echo "Re-run with --force to replace it."
    exit 0
fi

if security find-certificate -c "$CERT_NAME" "$KEYCHAIN" >/dev/null 2>&1; then
    echo "Certificate \"$CERT_NAME\" already exists in your keychain; reusing it."
else
    echo "Creating self-signed certificate \"$CERT_NAME\"…"
    WORK="$(mktemp -d)"
    trap 'rm -rf "$WORK"' EXIT
    cat > "$WORK/openssl.cnf" <<EOF
[req]
distinguished_name = dn
x509_extensions = ext
prompt = no
[dn]
CN = $CERT_NAME
[ext]
basicConstraints = critical,CA:false
keyUsage = critical,digitalSignature
extendedKeyUsage = critical,codeSigning
EOF
    $OPENSSL req -x509 -newkey rsa:2048 -nodes -days 3650 \
        -keyout "$WORK/key.pem" -out "$WORK/cert.pem" -config "$WORK/openssl.cnf" 2>/dev/null
    PASS="$($OPENSSL rand -hex 12)"
    $OPENSSL pkcs12 -export -inkey "$WORK/key.pem" -in "$WORK/cert.pem" \
        -name "$CERT_NAME" -out "$WORK/id.p12" -passout "pass:$PASS"
    security import "$WORK/id.p12" -k "$KEYCHAIN" -P "$PASS" \
        -T /usr/bin/codesign -T /usr/bin/security >/dev/null
    if [[ "$SKIP_TRUST" != "1" ]]; then
        echo "macOS will now ask for your password to trust the certificate for code signing."
        security add-trusted-cert -r trustRoot -p codeSign -k "$KEYCHAIN" "$WORK/cert.pem"
    fi
fi

cat > "$CONFIG_PATH" <<EOF
// Generated by scripts/setup-local-signing.sh. Ignored by Git.
CODE_SIGN_STYLE = Manual
CODE_SIGN_IDENTITY = $CERT_NAME
DEVELOPMENT_TEAM =
EOF

echo "Wrote Configuration/LocalSigning.xcconfig."
echo "Build and run in Xcode (or xcodebuild). If Xcode or codesign asks to use the"
echo "key, choose \"Always Allow\"."
